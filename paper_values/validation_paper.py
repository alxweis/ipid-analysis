"""Read immutable validation paper sidecars; never import analysis or render code."""

from functools import lru_cache
import hashlib
import json
import math
from pathlib import Path

from paper_values.cache import verify_file

CLASSES = (
    "REFLECTION",
    "CONSTANT",
    "SINGLE",
    "PER_CONNECTION",
    "PER_DESTINATION",
    "PER_BUCKET",
    "MULTI",
    "RANDOM",
)
CONDITIONS = ("ideal", "lossy", "reordered", "lossy-reordered")
MASS = {
    "ideal": "mass-4x25-classifier-confusion-ideal",
    "lossy": "mass-4x25-classifier-confusion-lossy-vs-lossy-reordered",
    "reordered": "mass-4x25-classifier-confusion-lossy-vs-reordered",
    "lossy-reordered": "mass-4x25-classifier-confusion-lossy-vs-lossy-reordered",
}
E2E = "e2e-classifier-confusion-ideal"
FIGURES = {
    *MASS.values(),
    E2E,
    *(f"mass-4x25-{method}-score-cdf-{c}" for method in ("random", "nist") for c in CONDITIONS),
}
MODEL_FILES = (
    "classifier_validation_preparation.py",
    "classifier_validation_parallel.py",
    "classifier_validation.py",
    "strategies.py",
    "random_classifier_candidate.py",
    "empirical_random_uniformity.py",
    "increment_uniformity.py",
    "nist_short_sequence.py",
    "synthetic_mass_sequences.py",
    "plot_random_structure_score_cdf.py",
)


def field(value, path):
    for key in path:
        value = value[key]
    return value


def metrics(value, samples):
    if value["classes"] != list(CLASSES) or value["predicted_classes"] != [
        *CLASSES,
        "UNCLASSIFIED",
    ]:
        raise ValueError("unexpected paper validation class order")
    counts = value["counts"]
    if len(counts) != 8 or any(
        len(row) != 9 or any(type(n) is not int or n < 0 for n in row) for row in counts
    ):
        raise ValueError("invalid paper validation confusion counts")
    supports = [sum(row) for row in counts]
    expected = [1000 if i < 2 else samples for i in range(8)]
    if supports != expected or supports != value["supports"]:
        raise ValueError("paper validation population differs from its model")
    accuracy = sum(counts[i][i] for i in range(8)) / sum(supports)
    balanced = sum(counts[i][i] / supports[i] for i in range(8)) / 8
    for key, expected_value in [("accuracy", accuracy), ("balanced_accuracy", balanced)]:
        if not math.isclose(value[key], expected_value, rel_tol=1e-12, abs_tol=1e-12):
            raise ValueError("paper validation accuracy disagrees with exact counts")
    if value["unclassified_count"] != sum(row[-1] for row in counts):
        raise ValueError("paper validation Unclassified count mismatch")
    for i, k in enumerate(CLASSES):
        correct = counts[i][i]
        predicted = sum(row[i] for row in counts)
        for key, fraction in [
            ("recall_by_class", correct / supports[i]),
            ("precision_by_class", correct / predicted if predicted else 0),
        ]:
            if not math.isclose(value[key][k], fraction, rel_tol=1e-12, abs_tol=1e-12):
                raise ValueError("paper validation class metric disagrees with counts")
        for j, n in enumerate(counts[i]):
            if not math.isclose(
                value["percentages"][i][j], 100 * n / supports[i], rel_tol=1e-12, abs_tol=1e-12
            ):
                raise ValueError("paper validation percentages disagree with counts")
    return value


class PaperValidation:
    def __init__(self, root):
        self.root = root
        self.load = lru_cache(maxsize=12)(self.load)
        self.code = lru_cache(maxsize=1)(self.code)

    def code(self):
        root = Path(__file__).resolve().parents[1] / "ipid_analysis"
        return {
            name: hashlib.sha256((root / name).read_bytes()).hexdigest() for name in MODEL_FILES
        }

    def path(self, figure):
        if figure not in FIGURES:
            raise ValueError("unknown paper validation figure")
        directory = self.root / ("nist-baseline" if "-nist-score-" in figure else "")
        return directory / (figure + "__paper.json")

    def load(self, figure):
        if self.root is None:
            return None
        path = self.path(figure)
        if not path.is_file():
            return None
        verify_file(path)
        if path.stat().st_size > 4 << 20:
            raise ValueError("oversized validation paper metadata")
        value = json.loads(path.read_text(encoding="utf-8"))
        if (
            value.get("version") != 1
            or value.get("paper_ready") is not True
            or value.get("figure") != figure
        ):
            raise ValueError("invalid validation paper identity")
        model = value["validation"]
        if model.get("model_sources") != self.code():
            raise ValueError("paper validation was generated by different classifier/model code")
        if (
            model.get("samples_per_nontrivial_class"),
            model.get("trivial_samples_per_class"),
            model.get("null_samples"),
        ) != (100000, 1000, 1000000):
            raise ValueError("paper validation is not a production-profile result")
        if (
            model.get("random_threshold"),
            model.get("nist_threshold"),
            model.get("random_score_version"),
        ) != (4.0383019016847365e-5, 0.0005, "increment-pearson-gap-min-v4"):
            raise ValueError("paper validation thresholds/score differ from production")
        if (
            type(model.get("seed")) is not int
            or model["seed"] < 0
            or model.get("random_null_seed") != 20260927
            or model.get("nist_null_seed") != 20260930
        ):
            raise ValueError("invalid validation data/reference seed metadata")
        if "panels" in value:
            expected_conditions = {c for c, stem in MASS.items() if stem == figure}
            conditions = [panel["condition"] for panel in value["panels"]]
            if (
                len(conditions) != len(expected_conditions)
                or set(conditions) != expected_conditions
            ):
                raise ValueError("paper validation panels do not match the figure")
            for panel in value["panels"]:
                if panel["condition"] not in CONDITIONS:
                    raise ValueError("unknown Mass validation condition")
                metrics(panel["metrics"], 100000)
        elif figure == E2E:
            if (
                value["model"].get("version"),
                value["model"].get("rt_observations"),
                value["model"].get("fi_new_observations"),
            ) != ("paired-116-v1", 16, 100):
                raise ValueError("unexpected paired RT/FI model")
            rt = metrics(value["e2e_rt"], 100000)
            for i, k in enumerate(CLASSES):
                row = rt["counts"][i]
                route = value["e2e_routing"][k]
                if row[6:8] != [0, 0] or route != {
                    "support": sum(row),
                    "forwarded_to_fi": row[-1],
                    "retained_rt_counts": [*row[:-1], 0],
                }:
                    raise ValueError("E2E routing differs from actual RT UNCLASSIFIED decisions")
            for c in CONDITIONS:
                final = metrics(value["e2e"][c], 100000)
                for i, k in enumerate(CLASSES):
                    retained = value["e2e_routing"][k]["retained_rt_counts"]
                    remainder = [n - r for n, r in zip(final["counts"][i], retained, strict=True)]
                    if (
                        min(remainder) < 0
                        or sum(remainder) != value["e2e_routing"][k]["forwarded_to_fi"]
                    ):
                        raise ValueError("E2E lost targets or changed retained RT decisions")
        else:
            method = "nist" if "-nist-score-" in figure else "random"
            condition = figure.removeprefix(f"mass-4x25-{method}-score-cdf-")
            if (value.get("method"), value.get("condition"), value.get("threshold")) != (
                method,
                condition,
                model[method + "_threshold"],
            ):
                raise ValueError("CDF identity/cutoff differs from its model")
            for i, k in enumerate(CLASSES):
                summary = value["summary_by_strategy"][k]
                n, ok = summary["count"], summary["random_compatible_count"]
                if n != (1000 if i < 2 else 100000) or type(ok) is not int or not 0 <= ok <= n:
                    raise ValueError("invalid CDF score compatibility counts")
        return value, (str(path),)

    def figure(self, figure):
        loaded = self.load(figure)
        if loaded is None:
            return None, ()
        _, sources = loaded
        pdf = self.path(figure).with_suffix(".pdf")
        if not pdf.is_file():
            return None, ()
        verify_file(pdf)
        with pdf.open("rb") as stream:
            if stream.read(5) != b"%PDF-":
                raise ValueError("validation paper file has no PDF signature")
        relative = pdf.relative_to(self.root)
        return "reports/figures/classifier-validation/" + relative.as_posix(), (*sources, str(pdf))

    def read(self, spec):
        figure = spec["figure"]
        if spec["stat"] == "paper-figure":
            return self.figure(figure)
        loaded = self.load(figure)
        if loaded is None:
            return None, ()
        value, sources = loaded
        stat = spec["stat"]
        if stat == "paper-e2e":
            record = value["e2e"][spec["condition"]]
            measure = spec["measure"]
            if measure == "total":
                result = sum(record["supports"])
            elif measure == "correct":
                result = sum(record["counts"][i][i] for i in range(8))
            elif measure == "unclassified-pct":
                result = 100 * record["unclassified_count"] / sum(record["supports"])
            else:
                result = record[measure]
        elif stat == "paper-routing":
            record = value["e2e_routing"][spec["class"]]
            result = (
                100 * record["forwarded_to_fi"] / record["support"]
                if spec["measure"] == "forwarded-pct"
                else record[spec["measure"]]
            )
        elif stat == "paper-rejection":
            record = value["summary_by_strategy"]["RANDOM"]
            result = 100 * (record["count"] - record["random_compatible_count"]) / record["count"]
        else:
            result = field(value, spec["field"])
        if "factor" in spec:
            if (
                type(result) not in (int, float)
                or not math.isfinite(result)
                or not 0 <= result <= 1
            ):
                raise ValueError("invalid paper validation fraction")
            result *= spec["factor"]
        return result, sources

    def legacy(self, spec):
        """Preserve existing public keys, preferring verified new sidecars."""
        if spec.get("stat") == "figure":
            figure = spec["filename"].removesuffix(".pdf")
            if figure in FIGURES and self.load(figure) is not None:
                return self.figure(figure)
            return None
        datasets = spec.get("datasets", ())
        path = spec.get("field", ())
        if path and path[0] == "datasets":
            datasets = (path[1],)
        if not datasets:
            return None
        records = {}
        sources = []
        for dataset in datasets:
            if dataset == "base-4x4-ideal":
                loaded = self.load(E2E)
                if loaded is None:
                    return None
                doc, src = loaded
                matrix = doc["e2e_rt"]
                limit = 6
                sequence_length = 16
            else:
                condition = dataset.removeprefix("mass-4x25-")
                if condition not in MASS:
                    return None
                loaded = self.load(MASS[condition])
                if loaded is None:
                    return None
                doc, src = loaded
                selected = [p["metrics"] for p in doc["panels"] if p["condition"] == condition]
                if len(selected) != 1:
                    raise ValueError("missing/ambiguous Mass validation panel")
                matrix = selected[0]
                limit = 8
                sequence_length = 100
            sources.extend(src)
            records[dataset] = {
                "sequence_length": sequence_length,
                "loss_pct": 20 if "lossy" in dataset else 0,
                "reordering_pct": 20 if "reordered" in dataset else 0,
                "metrics": {
                    "accuracy": sum(matrix["counts"][i][i] for i in range(limit))
                    / sum(matrix["supports"][:limit]),
                    "classes": {
                        k: {"support": matrix["supports"][i], "correct": matrix["counts"][i][i]}
                        for i, k in enumerate(CLASSES)
                    },
                },
            }
        if spec.get("stat") == "minimum-recall":
            result = min(
                100
                * records[d]["metrics"]["classes"][k]["correct"]
                / records[d]["metrics"]["classes"][k]["support"]
                for d in datasets
                for k in spec["classes"]
            )
        else:
            result = field({"datasets": records}, path)
            if spec.get("stat") == "class-error-pct":
                result = 100 * (result["support"] - result["correct"]) / result["support"]
            elif "factor" in spec:
                result *= spec["factor"]
        return result, tuple(dict.fromkeys(sources))

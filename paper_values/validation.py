"""Read the small current synthetic-validation summary, without importing analysis code."""

from functools import lru_cache
import hashlib
import json
import math
from pathlib import Path

from paper_values.cache import verify_file


class Validation:
    def __init__(self, root):
        self.root = Path(root) if root is not None else None
        self.load = lru_cache(maxsize=1)(self.load)

    def load(self):
        if self.root is None:
            return None
        path = self.root / "classifier-validation-summary.json"
        if not path.is_file():
            return None
        verify_file(path)
        data = json.loads(path.read_text(encoding="utf-8"))
        if (
            not isinstance(data, dict)
            or data.get("schema_version") != 1
            or data.get("production_profile") is not True
        ):
            raise ValueError("validation summary is not a current production-profile result")
        code_root = Path(__file__).resolve().parents[1] / "ipid_analysis"
        expected = {
            name: hashlib.sha256((code_root / name).read_bytes()).hexdigest()
            for name in (
                "strategies.py",
                "random_classifier_candidate.py",
                "increment_uniformity.py",
                "empirical_random_uniformity.py",
                "classifier_validation.py",
            )
        }
        if data.get("classifier_sources") != expected:
            raise ValueError("validation summary was generated by different classifier code")
        return data

    def read(self, spec):
        data = self.load()
        if data is None:
            return None, ()
        source = self.root / "classifier-validation-summary.json"
        stat = spec.get("stat")
        if stat == "figure":
            info = data["figures"][spec["figure"]]
            if info["filename"] != spec["filename"]:
                raise ValueError("validation figure identity differs from its definition")
            path = self.root / spec["filename"]
            if not path.is_file():
                return None, ()
            verify_file(path)
            content = path.read_bytes()
            if (
                not content.startswith(b"%PDF-")
                or len(content) != info["size_bytes"]
                or hashlib.sha256(content).hexdigest() != info["sha256"]
            ):
                raise ValueError("validation PDF differs from its generating summary")
            sources = (str(source), str(path))
            paper = path.with_name(path.stem + "__paper.pdf")
            if paper.is_file():
                verify_file(paper)
                with paper.open("rb") as stream:
                    if stream.read(5) != b"%PDF-":
                        raise ValueError("validation paper file has no PDF signature")
                path = paper
                sources += (str(paper),)
            # A global generated figure has the same destination as the analysis output.
            return "reports/figures/classifier-validation/" + path.name, sources
        if stat == "minimum-recall":
            classes = [
                data["datasets"][name]["metrics"]["classes"][strategy]
                for name in spec["datasets"]
                for strategy in spec["classes"]
            ]
            return min(self.class_percentage(c) for c in classes), (str(source),)
        value = data
        for key in spec["field"]:
            value = value[key]
        if stat == "class-error-pct":
            value = self.class_percentage(value, error=True)
        elif "factor" in spec:
            if type(value) not in (int, float) or not math.isfinite(value) or not 0 <= value <= 1:
                raise ValueError("invalid validation accuracy fraction")
            value *= spec["factor"]
        return value, (str(source),)

    @staticmethod
    def class_percentage(record, *, error=False):
        support, correct = record["support"], record["correct"]
        if not (type(support) is int and type(correct) is int and 0 <= correct <= support):
            raise ValueError("invalid validation class counts")
        if not support:
            raise ValueError("required validation class has no samples")
        return 100.0 * (support - correct if error else correct) / support
